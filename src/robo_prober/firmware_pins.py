"""Generate the firmware's per-chip pin tables from the board catalog.

catalog.py is the only place pin facts live. The firmware cannot import
Python, so this writes them into a C++ header that is checked in::

    python -m robo_prober.firmware_pins          # rewrite pin_profiles.h
    python -m robo_prober.firmware_pins --check  # exit 1 if it is stale

The test suite runs the check too.
"""
from __future__ import annotations

import sys
from pathlib import Path

from .catalog import BOARD_PROFILES, FIRMWARE_CHIPS, PIN_ADC, PIN_INPUT_ONLY, PIN_LAST, PIN_USABLE, discovery_pin_flags

GPIO_COUNT = 49  # GPIO0..48, the largest ESP32-family chip; the firmware uses the same size
HEADER = Path(__file__).resolve().parents[2] / "firmware" / "esp32_robo_prober" / "src" / "pin_profiles.h"


def chip_flags(chip: str) -> list[int]:
    flags = discovery_pin_flags(FIRMWARE_CHIPS[chip])
    return [flags.get(gpio, 0) for gpio in range(GPIO_COUNT)]


def render_header() -> str:
    lines = [
        "// GENERATED by `python -m robo_prober.firmware_pins` from src/robo_prober/catalog.py.",
        "// Do not edit by hand: change the catalog and regenerate (a test checks they match).",
        "//",
        "// One byte per GPIO number. 0 = not on the chip, or wired to flash/PSRAM, USB or the",
        "// host UART: never touched. Bits describe the pin, they never permit driving it.",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace rp {",
        "namespace pins {",
        "",
        f"constexpr int kGpioCount = {GPIO_COUNT};",
        f"constexpr uint8_t kUsable = {PIN_USABLE};     // may be surveyed (read)",
        f"constexpr uint8_t kLast = {PIN_LAST};       // boot strapping / JTAG: last, and only with confirmation",
        f"constexpr uint8_t kInputOnly = {PIN_INPUT_ONLY};  // never driven",
        f"constexpr uint8_t kAdc = {PIN_ADC};        // has an ADC channel",
        "",
    ]
    for chip in FIRMWARE_CHIPS:
        values = chip_flags(chip)
        profile = FIRMWARE_CHIPS[chip]
        lines.append(f"// {profile}")
        lines.append(f'constexpr const char *k_{chip}_profile = "{profile}";')
        lines.append(f'constexpr const char *k_{chip}_model = "{BOARD_PROFILES[profile]["platform"]}";')
        lines.append(f"constexpr uint8_t k_{chip}[kGpioCount] = {{")
        for start in range(0, GPIO_COUNT, 16):
            row = ", ".join(str(value) for value in values[start:start + 16])
            lines.append(f"    {row},  // GPIO{start}..")
        lines.append("};")
        lines.append("")
    lines += ["}  // namespace pins", "}  // namespace rp", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render_header()
    if "--check" in argv:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(f"{HEADER} is stale; run python -m robo_prober.firmware_pins", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
